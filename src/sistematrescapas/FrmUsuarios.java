    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String elCorreo = txtCorreo.getText().trim();
        String losNombres = txtNombres.getText().trim();
        String losApellidos = txtApellidos.getText().trim();
        String laClave = txtClave.getText().trim();
        int elNivel = -1;
        if (rdbUsuario.isSelected())
            elNivel = 1;
        else if (rdbAsistente.isSelected())
            elNivel = 2;
        else
            elNivel = 3;
        
        if (validarCamposLlenos()) {
            usuariosDAO.setCorreos(elCorreo);
            usuariosDAO.setNombres(losNombres);
            usuariosDAO.setApellidos(losApellidos);
            usuariosDAO.setClaves(laClave);
            usuariosDAO.setNiveles(elNivel);
            boolean resultado = usuariosLogica.insertarUsuario(usuariosDAO);
            if (resultado) {
                JOptionPane.showMessageDialog(null, "Error al insertar el registro...", "Error", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(null, "Se insertó el registro...", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                limpiarControles();
            }
        } else {
            JOptionPane.showMessageDialog(null, "Debe de llenar todos los campos antes de guardar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

